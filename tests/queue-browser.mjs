import {chromium,webkit} from 'playwright';
import assert from 'node:assert/strict';
const engine=process.env.WEBKIT?webkit:chromium;
const b=await engine.launch({args:process.env.WEBKIT?[]:['--no-sandbox']});
const p=await b.newPage({viewport:{width:1194,height:834},hasTouch:true});
const url=process.env.POS_URL||'http://127.0.0.1:8765';
const errors=[];p.on('pageerror',e=>errors.push(e.message));
let posts=0;await p.route('https://script.google.com/**',r=>{posts++;return r.abort();});
try{
 await p.goto(url);
 await p.evaluate(()=>localStorage.setItem('cocoa-pos-sheet-key-v1','fixture-only-not-real-key'));
 await p.locator('.menu-card[data-id="0"]').tap();
 await p.getByRole('button',{name:'สรุปออเดอร์',exact:true}).click({timeout:5000});
 await p.getByLabel('ชื่อลูกค้า / หมายเหตุ').fill('ลูกค้า A <b>');
 await p.getByRole('button',{name:'ยืนยันเข้าคิวรอจ่าย',exact:true}).click();
 assert.equal(await p.locator('#cup-count').innerText(),'0');
 assert.match(await p.locator('#today-total').innerText(),/0\.00/);
 assert.equal(posts,0);
 await p.locator('.menu-card[data-id="8"]').tap();
 await p.getByRole('button',{name:'สรุปออเดอร์',exact:true}).click();
 await p.getByLabel('ชื่อลูกค้า / หมายเหตุ').fill('ลูกค้า B');
 await p.getByRole('button',{name:'ยืนยันเข้าคิวรอจ่าย',exact:true}).click();
 await p.reload();
 await p.locator('.menu-card[data-id="6"]').tap(); // third draft must survive paying A
 await p.getByRole('button',{name:/คิวรอจ่าย/}).first().click();
 assert.equal(await p.locator('.queue-order').count(),2);
 assert.match(await p.locator('.queue-order').first().innerText(),/ลูกค้า A <b>/);
 assert.equal(await p.locator('.queue-order b').count(),0);
 await p.locator('.queue-order').first().getByRole('button',{name:'รับเงิน',exact:true}).click();
 await p.getByLabel('รับเงิน (บาท)').fill('1');await p.locator('#pay').click();
 assert.match(await p.locator('#payment-error').innerText(),/เงินไม่พอ/);
 await p.getByLabel('รับเงิน (บาท)').fill('100');await p.locator('#pay').click();
 await p.waitForSelector('#receipt[open]');
 assert.match(await p.locator('#receipt').innerText(),/31\.00/);
 assert.equal(await p.locator('#cup-count').innerText(),'1');
 const sales=await p.evaluate(()=>JSON.parse(localStorage.getItem('cocoa-pos-v1')));
 assert.equal(sales.length,1);assert.equal(sales[0].total,69);
 await p.getByRole('button',{name:'ออเดอร์ถัดไป',exact:true}).click();
 await p.reload();
 await p.getByRole('button',{name:/คิวรอจ่าย/}).first().click();
 assert.equal(await p.locator('.queue-order').count(),1);
 assert.match(await p.locator('.queue-order').innerText(),/ลูกค้า B/);
 await p.locator('.queue-order').getByRole('button',{name:'รับเงิน',exact:true}).click();
 await p.getByRole('button',{name:'โอนเงิน',exact:true}).click();await p.locator('#pay').click();
 await p.waitForSelector('#receipt[open]');
 assert.equal(await p.evaluate(()=>JSON.parse(localStorage.getItem('cocoa-pos-v1')).length),2);
 assert.match(await p.locator('#today-total').innerText(),/148\.00/);
 await p.getByRole('button',{name:'ออเดอร์ถัดไป',exact:true}).click();
 await p.getByRole('button',{name:/คิวรอจ่าย/}).first().click();
 assert.equal(await p.locator('.queue-order').count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS queue: 2 unpaid orders persisted, no unpaid upload/revenue, cash/transfer paid independently, third draft retained, customer text escaped; '+engine.name());
}finally{await b.close();}
